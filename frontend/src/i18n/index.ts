// Traduções v0.5.0 para as línguas que herdam do inglês (RNF-007): aplicadas
// uma única vez no arranque do módulo, antes de qualquer chamada a `t`.
Object.entries(v050Translations).forEach(([lang, dict]) => {
  const target = translations[lang as Lang];
  if (target && dict) Object.assign(target, dict);
});

export function t(lang: Lang, key: keyof Translations, vars?: Record<string, string | number>): string {
  let str = translations[lang]?.[key] ?? translations['en'][key] ?? key;
  if (vars) Object.entries(vars).forEach(([k, v]) => { str = str.replace(`{${k}}`, String(v)); });
  return str;
}
